#!/usr/bin/env python3
"""Derive vtable-slot names from RTTI layout and emit an IDA rename script.

Names here come from the binary's own structure, not from resemblance to another
build. A slot in `CFoo`'s vtable holds a `CFoo` method — that much is certain even
when the method's purpose is not, so an unidentified slot is named
`CFoo::vfunc<N>` rather than left to inherit a guess from elsewhere.

Two shapes are recognised, both inferred from the data rather than hardcoded:

* **destructor pair** — two adjacent slots holding small functions that sit at
  lower addresses than the rest of the class's methods. The Itanium ABI emits
  D1 (complete) and D0 (deleting) together, and they are tiny.
* **lifecycle block** — the trailing five slots of a `CProc`-derived screen class,
  which this codebase orders Begin/Start/Run/Stop/End.

Anything before the lifecycle block is an extra virtual the class declared itself.

    vtable_names.py <binary> --names current.json --out apply.py
"""

from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rtti_vtables import Binary, find_typeinfos, find_vtables, load_names  # noqa: E402

LIFECYCLE = ("Begin", "Start", "Run", "Stop", "End")
SMALL = 80          # destructor stubs here run 11-57 bytes
PAIR_GAP = 64       # D1 and D0 are emitted adjacently


def classify(table: dict, sizes: dict) -> dict:
    """slot index -> derived name suffix, for one vtable."""
    slots = table["slots"]
    owner = table["class"]
    result: dict = {}

    if table["secondary"]:
        # Secondary-base thunks: real, but they only adjust `this` and jump.
        for index, _ in enumerate(slots):
            result[index] = f"{owner}::_thunk{index}"
        return result

    remaining = list(range(len(slots)))

    # Only look for a destructor pair where the slot count allows one. A 5-slot
    # class is lifecycle-only: hunting a pair there finds two small lifecycle
    # methods (CIdle's 24-byte Begin and 1-byte Start) and demotes them.
    if len(slots) in (2, len(LIFECYCLE) + 2):
        for i in range(len(slots) - 1):
            a, b = slots[i], slots[i + 1]
            sa, sb = sizes.get(a, 0), sizes.get(b, 0)
            if not (0 < sa <= SMALL and 0 < sb <= SMALL):
                continue
            # Adjacency and sitting below every other method are the reliable
            # signals; size alone is not — CSelect's pair is 53/57 bytes.
            if not (0 < b - a <= PAIR_GAP):
                continue
            rest = [addr for j, addr in enumerate(slots) if j not in (i, i + 1)]
            if rest and max(a, b) >= min(rest):
                continue
            result[i] = f"{owner}::~{owner}"
            result[i + 1] = f"{owner}::~{owner}_deleting"
            remaining = [j for j in remaining if j not in (i, i + 1)]
            break

    # Trailing five slots are the CProc lifecycle.
    if len(remaining) >= len(LIFECYCLE):
        tail = remaining[-len(LIFECYCLE):]
        for name, index in zip(LIFECYCLE, tail):
            result[index] = f"{owner}::{name}"
        remaining = remaining[:-len(LIFECYCLE)]

    # Anything left is a virtual this class declared before its overrides.
    for index in remaining:
        result[index] = f"{owner}::vfunc{index}"
    return result


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="vtable-names")
    parser.add_argument("binary")
    parser.add_argument("--names", required=True,
                        help="JSON {hex_address: current_name}")
    parser.add_argument("--sizes", required=True,
                        help="JSON {hex_address: size}")
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv[1:])

    binary = Binary(args.binary)
    tables = find_vtables(binary, find_typeinfos(binary))
    current = load_names(args.names)
    sizes = {int(k, 16): v for k, v in json.load(open(args.sizes)).items()}

    changes, kept = [], 0
    for table in tables:
        derived = classify(table, sizes)
        for index, addr in enumerate(table["slots"]):
            want = derived.get(index)
            if not want:
                continue
            have = current.get(addr, "")
            if have == want:
                kept += 1
                continue
            changes.append({"address": f"{addr:08x}", "was": have, "now": want,
                            "class": table["class"], "slot": index,
                            "size": sizes.get(addr, 0)})

    body = "\n".join(
        f'    (0x{c["address"]}, {c["now"]!r}),  # slot {c["slot"]} of {c["class"]}'
        f'  was: {c["was"][:44]}' for c in changes)
    script = f'''\
# Generated by rekit — vtable-slot names derived from this binary's RTTI.
#
# Every name below is grounded in the vtable layout: the class comes from the
# type_info the vtable points at, and the slot position gives the method. Where
# the method could not be identified it is named CFoo::vfuncN — which states what
# is known (the owning class) without asserting what is not.
#
# Run in IDA on the Exceed 40316 database.

import idc

RENAMES = [
{body}
]

def main():
    applied = 0
    for ea, name in RENAMES:
        if idc.set_name(ea, name, idc.SN_NOWARN | idc.SN_FORCE):
            applied += 1
    print("rekit: applied %d of %d vtable-slot names" % (applied, len(RENAMES)))

main()
'''
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(script)

    print(f"vtables {len(tables)}  slots renamed {len(changes)}  already correct {kept}")
    for c in changes:
        print(f"  {c['class']:<18} slot {c['slot']}  0x{c['address']}  "
              f"{c['size']:>5}B  {c['was'][:38]:<38} -> {c['now']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
